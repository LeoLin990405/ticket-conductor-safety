// Embeds skills/*.md into src/skills/packs.generated.js. The Forge bundle
// does not ship the skills/ directory, so the loader falls back to this.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export function buildPacksSource() {
  const dir = join(root, 'skills');
  const files = readdirSync(dir)
    .filter((n) => n.endsWith('.md') && !n.startsWith('.') && !n.startsWith('_'))
    .sort();
  const entries = Object.fromEntries(files.map((n) => [n, readFileSync(join(dir, n), 'utf8')]));
  return '// Generated by scripts/gen-skill-packs.mjs. Do not edit.\n'
    + `export const EMBEDDED_SKILL_FILES = Object.freeze(${JSON.stringify(entries, null, 2)});\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, 'src/skills/packs.generated.js'), buildPacksSource());
}
