/**
 * Print the irreversible-action table, write the evidence files, and exit
 * 1 when a row fails.
 *
 *   npm run safety-eval
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { formatSafetyReport, runSafetyEval } from '../src/safety/eval.js';
import { formatNaiveComparison, runNaiveComparison } from '../src/safety/naiveAgent.js';
import { terminalSvg } from '../src/safety/terminalSvg.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const rows = await runSafetyEval();
const comparison = await runNaiveComparison();
const table = formatSafetyReport(rows);
const naive = formatNaiveComparison(comparison);
console.log(table);
console.log('');
console.log(naive);

const failed = rows.filter((row) => row.result !== 'PASS').length;
const report = {
  command: 'npm run safety-eval',
  node: process.version,
  pass: rows.length - failed,
  fail: failed,
  rows,
  comparison: {
    baselineIrreversibleWrites: comparison.baseline.irreversibleWrites,
    guardedIrreversibleWrites: comparison.guarded.irreversibleWrites,
    guardedBlocked: comparison.guarded.blocked,
    attempts: comparison.attempts,
    baseline: comparison.baseline,
    guarded: comparison.guarded,
  },
};

mkdirSync(join(root, 'docs/evidence'), { recursive: true });
mkdirSync(join(root, 'docs/media'), { recursive: true });
writeFileSync(join(root, 'docs/evidence/safety-eval.json'), `${JSON.stringify(report, null, 2)}\n`);
writeFileSync(join(root, 'docs/evidence/safety-eval.md'), markdownTable(rows, comparison));
writeFileSync(join(root, 'docs/failure-matrix.md'), failureMatrix(rows));
writeFileSync(join(root, 'docs/media/safety-eval.txt'), `${table}\n\n${naive}\n`);
writeFileSync(join(root, 'docs/media/safety-eval.svg'), terminalSvg('npm run safety-eval', [
  `node ${process.version}`,
  `${report.pass} pass, ${report.fail} fail`,
  `baseline irreversible writes: ${comparison.baseline.irreversibleWrites}`,
  `guarded irreversible writes: ${comparison.guarded.irreversibleWrites}`,
  `guarded blocked: ${comparison.guarded.blocked} of ${comparison.attempts.length}`,
]));

if (failed > 0) {
  process.exitCode = 1;
}

/**
 * @param {Array<{id?: string, class?: string, property: string, expected?: string, result: string, detail?: string}>} items
 * @param {{baseline: {irreversibleWrites: number}, guarded: {irreversibleWrites: number, blocked: number}}} compared
 */
function markdownTable(items, compared) {
  const lines = [
    '# Safety eval',
    '',
    'Generated by `npm run safety-eval`. Do not edit this file by hand.',
    '',
    `Node ${process.version}. ${items.length - items.filter((row) => row.result !== 'PASS').length} pass, ${items.filter((row) => row.result !== 'PASS').length} fail.`,
    '',
    `Baseline irreversible writes: ${compared.baseline.irreversibleWrites}. Guarded irreversible writes: ${compared.guarded.irreversibleWrites}.`,
    '',
    '| id | class | check | result |',
    '|---|---|---|---|',
  ];
  for (const row of items) {
    lines.push(`| ${cell(row.id || '')} | ${cell(row.class || '')} | ${cell(row.property)} | ${row.result} |`);
  }
  lines.push('');
  return lines.join('\n');
}

/**
 * @param {Array<{id?: string, class?: string, property: string, expected?: string, result: string, detail?: string}>} items
 */
function failureMatrix(items) {
  const named = items.filter((row) => row.id && row.class);
  const lines = [
    '# Failure-state matrix',
    '',
    'Generated by `npm run safety-eval`. Each row is one scenario in `src/safety/failures.js`. The result column is the observed result from that command, not a hand-written status.',
    '',
    'The classes are the ones the challenge asks entrants to try: ambiguous instructions, missing information, prompt injection, unauthorized requests, unusual edge cases, bypasses of the approval mechanism, expired approvals, malformed tool arguments, and timeouts (including a partial apply and a second delivery while a call is in flight). `fail-safe` is the shared grant store refusing when its write throws.',
    '',
    '| class | scenario | expected | observed |',
    '|---|---|---|---|',
  ];
  for (const row of named) {
    const observed = row.result === 'PASS' ? 'PASS' : `FAIL: ${row.detail || ''}`;
    lines.push(`| ${cell(row.class)} | ${row.id} | ${cell(row.expected || row.property)} | ${cell(observed)} |`);
  }
  lines.push('');
  lines.push('Older confirmation checks (no token, the string "true", a public digest, handoff, budget drain, field undo) are in `docs/evidence/safety-eval.md`. They use the same command and do not have a failure-class id.');
  lines.push('');
  return lines.join('\n');
}

/**
 * @param {string} value
 */
function cell(value) {
  return String(value).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}
