// Writes src/store/entitySchema.generated.js from manifest.yml storage
// entities. The Forge adapter uses it to tell a transient KVS 422 (the record
// matches the deployed schema) from a real schema error.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export function buildEntitySchemaSource() {
  const manifest = parse(readFileSync(join(root, 'manifest.yml'), 'utf8'));
  const entities = manifest?.app?.storage?.entities ?? manifest?.modules?.storage?.entities
    ?? manifest?.storage?.entities ?? [];
  const out = {};
  for (const entity of entities) {
    out[entity.name] = Object.keys(entity.attributes ?? {}).sort();
  }
  return '// Generated by scripts/gen-entity-schema.mjs. Do not edit.\n'
    + `export const ENTITY_ATTRIBUTES = Object.freeze(${JSON.stringify(out, null, 2)});\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, 'src/store/entitySchema.generated.js'), buildEntitySchemaSource());
}
